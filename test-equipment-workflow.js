'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const store={},listeners={};
const app={innerHTML:'',addEventListener:(name,cb)=>listeners[name]=cb};
const toast={textContent:'',classList:{add(){},remove(){}}};
const doc={getElementById:id=>id==='app'?app:id==='toast'?toast:null,
 createElement:()=>({style:{},click(){}}),body:{appendChild(){}},addEventListener(){}};
const c={window:null,document:doc,localStorage:{getItem:k=>store[k]||null,setItem:(k,v)=>store[k]=v,removeItem:k=>delete store[k]},Date,JSON,Math,Set,Number,String,URL,URLSearchParams,Blob,Map,crypto:require('node:crypto').webcrypto,console,
 location:{hash:'',pathname:'/deskrawl-build-planner/',search:'',origin:'https://kanazawatokyo.github.io'},
 history:{replaceState(){}},setTimeout:()=>0,clearTimeout:()=>{},confirm:()=>true,prompt:()=>'保存版',fetch:()=>Promise.reject(Error('disabled'))};
c.window=c;c.addEventListener=()=>{};vm.createContext(c);
for(const file of ['master.js','calc.js','combat.js','stats-view.js','app.js'])
 vm.runInContext(fs.readFileSync(__dirname+'/'+file,'utf8'),c,{filename:file});
const click=(action,id,value)=>listeners.click({target:{closest:()=>({dataset:{action,id,value}})}});
const change=(kind,id,v,type='checkbox')=>listeners.change({target:{dataset:{change:kind,id},checked:Boolean(v),type,value:String(v)}});
let st=c.DBPApp.getState(),base=st.builds[0],initialCount=st.items.length;
const chestId=base.loadout.chest;
change('locked',chestId,true);
click('new-item');st=c.DBPApp.getState();
const candidate=st.items.at(-1);
assert.equal(candidate.nickname,'','new candidate should show the item definition, not generic nickname');
assert.equal(candidate.locked,false);
assert.deepEqual(candidate.primary,[],'new item must not inherit gear OP from locked current item');
assert.deepEqual(candidate.opLocks.primary,[],'new item must not inherit OP protections');
assert.equal(candidate.definitionId,'custom-chest','new item has an empty gear type');
change('definition',candidate.id,'unyielding','select-one');st=c.DBPApp.getState();
assert.equal(st.items.find(x=>x.id===candidate.id).definitionId,'unyielding','can select a different gear type');
assert.match(app.innerHTML,/data-action="equip"/);
assert.match(app.innerHTML,/この部位の装備候補/);
assert.match(app.innerHTML,/data-action="unequip"/);
click('equip',candidate.id);st=c.DBPApp.getState();
assert.equal(st.builds[0].loadout.chest,candidate.id,'equip works even when previous item was locked');
assert.equal(st.items.find(x=>x.id===chestId).locked,true,'original item stays locked');
click('delete-item',candidate.id);st=c.DBPApp.getState();
assert(!st.items.some(x=>x.id===candidate.id),'active candidate can be deleted');
assert(!st.builds[0].loadout.chest,'active candidate is unequipped during deletion');
assert(st.items.some(x=>x.id===chestId),'former locked gear still in storage');
click('equip',chestId);st=c.DBPApp.getState();
assert.equal(st.builds[0].loadout.chest,chestId);
click('new-build');assert.match(app.innerHTML,/現在の一式をコピーして始める/);
click('new-build-copy');st=c.DBPApp.getState();
assert.equal(st.builds.length,2);
const copied=st.builds[1];
assert.notEqual(copied.loadout.chest,chestId);
assert.equal(st.items.length,initialCount+11,'one independent copy per equipped slot');
assert(Object.values(copied.loadout).every(id=>st.items.find(x=>x.id===id)?.locked===false),'independent copies are editable');
assert(st.items.find(x=>x.id===chestId).locked,'original locked item remains locked');
assert.equal(st.builds[0].loadout.chest,chestId,'base loadout unchanged');
click('new-build');click('new-build-empty');st=c.DBPApp.getState();
assert.equal(st.builds.length,3);assert.equal(Object.keys(st.builds[2].loadout).length,0);
const weapon=st.builds[0].loadout.weapon;
assert.match(app.innerHTML,/未装備/);
assert.match(app.innerHTML,/data-action="equip"/,'candidate list visible when slot is empty');
click('equip',weapon);st=c.DBPApp.getState();
assert.equal(st.builds[2].loadout.weapon,weapon);
click('unequip');st=c.DBPApp.getState();
assert(!st.builds[2].loadout.weapon,'unequip clears only current slot');
assert(st.items.some(x=>x.id===weapon),'unequipped gear stays in storage');
click('delete-item',weapon);st=c.DBPApp.getState();
assert(!st.items.some(x=>x.id===weapon),'confirmation can delete a shared item');
assert(!st.builds[0].loadout.weapon,'all referencing builds lose only the deleted gear');
click('new-build');click('new-build-share');st=c.DBPApp.getState();
assert.equal(st.builds.length,4);
assert.equal(st.items.length,initialCount+11,'shared build does not duplicate gear');
assert.equal(st.schemaVersion,1,'persisted schema unchanged');
console.log('PASS: swap locked gear, delete active candidate, unequip, independent/blank/shared build, preserved data');
