'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const getSource=f=>fs.readFileSync(__dirname+'/'+f,'utf8');
const ctx={window:null,console,Math,JSON,Date,Set,Map,Number,String,Array,URL,URLSearchParams,Blob};
ctx.window=ctx;vm.createContext(ctx);
for(const f of ['master.js','pets.js','talents.js','calc.js','combat.js','combat-ui.js'])vm.runInContext(getSource(f),ctx,{filename:f});
const B=ctx.DBPCombat,C=ctx.DBPCalc,UI=ctx.DBPCombatUI;
const approx=(actual,expected,label)=>assert(Math.abs(actual-expected)<1e-7,label+': '+actual+' vs '+expected);
const eq=(slot,definitionId)=>({id:'id-'+slot,slot,definitionId,primary:[],secondary:'',upgrade:0,overrides:{}});
const inventory=[
 eq('shoulder','shoulder'),eq('legs','greaves'),eq('gloves','gauntlets'),eq('head','iron'),
 eq('neck','prism'),eq('boots','windcaller'),eq('chest','unyielding'),eq('belt','bottomless'),
 eq('weapon','grandmother'),eq('ring1','schrodinger'),eq('ring2','sage')
];
const gearDoc={items:inventory};
const loadout=Object.fromEntries(inventory.map(x=>[x.slot,x.id]));
const gearBuild={loadout};
const gear=B.equippedEffects(gearDoc,gearBuild);
assert.equal(Object.keys(gear.items).length,11,'only equipped slots produce powers');
assert.equal(gear.schrodingerRing,true);
assert.equal(B.equippedEffects(gearDoc,{loadout:{head:'id-gloves'}}).items.head,undefined,'mismatched slots must not work');
assert.equal(B.equippedEffects(gearDoc,{loadout:{legs:'other'}}).items.legs,undefined,'inventory item not equipped is ignored');
const stats={effective:{weaponDamage:100,damage:0,int:0,critChance:0,critDamage:0,
 lightning:100,fire:0,cold:0,arcane:0,poison:0,allDamage:10,armor:3500,mr:3500,dodge:0},breakdown:{}};
const setting={base:{int:0,critChance:0,critDamage:0,dodge:0}};
const attack={attackType:'strong',damageType:'lightning',skillPercent:100,skillFlat:0,heroLevel:70,enemyHealth:50,
 abilityId:'lightningStorm',elementalStacks:5};
const all=B.attack(stats,setting,attack,gear);
assert.equal(all.unique.stacks,5);
assert.equal(all.unique.stackBonus,100,'20% × 5 is added in element bucket');
approx(all.unique.prismBonus,50,'highest Lightning 200% × 25% on Prismatic Heart');
assert.equal(all.eleValue,250,'Lightning 100 + Pauldron 100 + Prism 50');
approx(all.elemMult,3.6,'Lightning 250% + Bonus All Damage 10% -> multiplier 3.6');
assert.equal(all.unique.greavesCrit,150);
assert.equal(all.unique.gauntletCrit,150);
assert.equal(all.critBonus,300,'Greaves + Gauntlets each add +150% Crit damage');
approx(all.unique.ironMult,1.2,'Iron Helm ordinary independent multiplier');
assert(all.layers.some(x=>x.key==='unique'&&Math.abs(x.factor-1.2)<1e-7));
assert(all.unique.sources.some(x=>x.key==='element'&&x.value===100),'show Pauldron contribution');
assert(all.unique.sources.some(x=>x.key==='element'&&x.value===50),'show Prism contribution');
assert(all.unique.sources.filter(x=>x.key==='critical').length===2,'both +150 Crit sources shown');
const noStacks=B.attack(stats,setting,{...attack,elementalStacks:0},gear);
assert.equal(noStacks.unique.stackBonus,0);
approx(noStacks.unique.prismBonus,25,'Prism amplifies existing highest element by 25%');
assert.equal(noStacks.eleValue,125);
assert(all.normal.final>noStacks.normal.final,'five stacks increase actual computed damage');
const elite=B.attack(stats,setting,{...attack,elite:true},gear);
approx(elite.unique.ironMult,1.4,'Iron Helm gets 40% vs Elite/Boss');
assert(elite.normal.final>all.normal.final,'Elite bonus increases final hit');
const one=B.attack(stats,setting,{...attack,elementalStacks:1},gear);
assert.equal(one.unique.stackBonus,20);
const baseNoGear=B.attack(stats,setting,attack);
assert.equal(baseNoGear.unique.stackBonus,0);
assert.equal(baseNoGear.unique.prismBonus,0);
assert.equal(baseNoGear.unique.greavesCrit,0);
assert.equal(baseNoGear.unique.gauntletCrit,0);
approx(baseNoGear.unique.ironMult,1);
assert(baseNoGear.normal.final<all.normal.final);
const generic=B.attack(stats,setting,{...attack,abilityId:'other'},gear);
assert.equal(generic.unique.gauntletCrit,0,'Stormcaller Gauntlets must not apply to any Lightning attack');
assert.equal(generic.unique.greavesCrit,150,'Greaves still work for Lightning skills');
const wrongAttack=B.attack(stats,setting,{...attack,attackType:'special'},gear);
assert.equal(wrongAttack.unique.gauntletCrit,150,'Lightning Storm automatically selects Strong Attack regardless of stale saved input');
assert.equal(wrongAttack.settings.attackType,'strong');
const fire=B.attack(stats,setting,{...attack,abilityId:'flameBreath',damageType:'fire'},gear);
assert.equal(fire.unique.stackBonus,100,'Pauldron also buffs Fire');
assert.equal(fire.unique.greavesCrit,150,'Greaves applies to Fire abilities');
assert.equal(fire.unique.gauntletCrit,0,'Gauntlet not applied to Fire');
const arcane=B.attack(stats,setting,{...attack,abilityId:'other',damageType:'arcane'},gear);
assert.equal(arcane.unique.stackBonus,100,'Pauldron also buffs Arcane');
assert.equal(arcane.unique.greavesCrit,150);
for(const type of ['physical','cold','poison']){
 const x=B.attack(stats,setting,{...attack,abilityId:'other',damageType:type},gear);
 assert.equal(x.unique.stackBonus,0,'Pauldron should not buff '+type);
 assert.equal(x.unique.greavesCrit,0,'Greaves should not buff '+type);
}
assert.equal(B.validateInput('elementalStacks',5.5),null);
assert.equal(B.validateInput('elementalStacks',6),null);
assert.equal(B.validateInput('elementalStacks',-1),null);
assert.equal(B.validateInput('elementalStacks',5),5);
assert.equal(B.validateInput('abilityId','invalid'),null);
const speed=B.attack(stats,setting,{...attack,windcallerActive:true},gear);
assert.equal(speed.unique.windcallerMove,50);
assert.equal(speed.normal.final,all.normal.final,'Windcaller movement cannot increase damage');
const dmg=B.defense(stats,setting,{incomingHit:10000,attackerLevel:70,defenseType:'lightning'},gear).selected;
const immune=B.defense(stats,setting,{incomingHit:10000,attackerLevel:70,defenseType:'lightning',unyieldingActive:true},gear).selected;
assert(dmg.afterFlat>0);
assert.equal(immune.afterFlat,0,'Unyielding 4-second invulnerability after proc');
assert.equal(immune.dodgeExpected,0);
assert.equal(immune.expectedCut,1);
assert(immune.layers.some(x=>x.key==='uniqueInvulnerable'));
assert(B.defense(stats,setting,{incomingHit:10000,attackerLevel:70,defenseType:'lightning',unyieldingActive:true}).selected.afterFlat>0,'cannot activate unequipped armor');
const beltStats=C.calc({items:[eq('belt','bottomless')]},{loadout:{belt:'id-belt'},settings:{aura:false,base:{},paragonPoints:{},talentPoints:{}}});
assert.equal(beltStats.sum.potionCharges,4,'Black Mist belt adds exactly +4 potion charges');
assert.equal(beltStats.breakdown.potionCharges.length,1,'passive counted only once');
const noBeltStats=C.calc({items:[]},{loadout:{},settings:{aura:false,base:{},paragonPoints:{},talentPoints:{}}});
assert.equal(noBeltStats.sum.potionCharges||0,0);
const html=UI.render(stats,{...setting,combat:attack},gear);
assert(html.includes('data-key="elementalStacks"'),'UI exposes stack selection');
assert(html.includes('data-key="abilityId"'),'UI exposes Storm vs generic ability selection');
assert(html.includes('data-key="windcallerActive"'),'UI exposes active movement buff');
assert(html.includes('data-key="unyieldingActive"'),'UI exposes active immunity');
assert(html.includes('装備固有効果の計算状態'));
assert(html.includes('エレメンタルバーストのポールドロン'));
assert(html.includes('秘術の刃のグリーヴ'));
assert(html.includes('ストームコーラーの篭手'));
assert(html.includes('プリズムの心臓'));
assert(html.includes('鉄の暴君の兜'));
assert(html.includes('装備固有の独立倍率'));
assert(html.includes('20% × 5スタック'),'contribution describes stack formula');
// End-to-end UI actions: edits persist in per-build combat scenarios and affect recalculation.
const events={},saved={},app={innerHTML:'',addEventListener:(k,fn)=>events[k]=fn};
const toast={textContent:'',classList:{add(){},remove(){}}};
ctx.document={getElementById:id=>id==='app'?app:id==='toast'?toast:null,createElement:()=>({style:{},files:[],click(){}}),body:{appendChild(){}},addEventListener(){}};
ctx.localStorage={getItem:k=>saved[k]??null,setItem:(k,v)=>saved[k]=v,removeItem:k=>delete saved[k]};
Object.assign(ctx,{crypto:require('node:crypto').webcrypto,setTimeout:()=>0,clearTimeout:()=>{},confirm:()=>true,prompt:()=> 'test',fetch:()=>Promise.reject(Error('no network')),location:{hash:'',pathname:'/',search:'',origin:'file://'},history:{replaceState(){}}});
ctx.window.addEventListener=()=>{};
vm.runInContext(getSource('pet-ui.js'),ctx,{filename:'pet-ui.js'});
vm.runInContext(getSource('talent-ui.js'),ctx,{filename:'talent-ui.js'});
vm.runInContext(getSource('stats-view.js'),ctx,{filename:'stats-view.js'});
vm.runInContext(getSource('app.js'),ctx,{filename:'app.js'});
const click=(action,value)=>events.click({target:{closest:()=>({dataset:{action,value}})}});
const change=(key,value,type='number')=>events.change({target:{id:'',type,checked:type==='checkbox'?value:false,value:String(value),dataset:{change:'combat',key}}});
click('tab-combat');
const state=()=>ctx.DBPApp.getState(),current=()=>state().builds[0].settings;
assert(app.innerHTML.includes('data-key="elementalStacks"'),'seed shoulder detected automatically');
assert(app.innerHTML.includes('エレメンタルバーストのポールドロン'));
change('elementalStacks',3);
change('abilityId','lightningStorm','select-one');
assert.equal(current().combat.attackType,'strong','choosing Lightning Storm auto-selects Strong Attack');
assert.equal(current().combat.damageType,'lightning','choosing Lightning Storm auto-selects Lightning');
change('windcallerActive',true,'checkbox');
change('unyieldingActive',true,'checkbox');
assert.equal(current().combat.elementalStacks,3);
assert.equal(current().combat.abilityId,'lightningStorm');
assert.equal(current().combat.windcallerActive,true);
assert.equal(current().combat.unyieldingActive,true);
assert.equal(JSON.parse(saved.deskrawl_planner_v01).builds[0].settings.combat.elementalStacks,3);
const badBefore=current().combat.elementalStacks;change('elementalStacks',7);
assert.equal(current().combat.elementalStacks,badBefore,'must reject stacks greater than 5');
const actual=B.attack(C.calc(state(),state().builds[0]),current(),current().combat,B.equippedEffects(state(),state().builds[0]));
assert.equal(actual.unique.stacks,3,'saved scenario and equipped items recomputed together');
assert.equal(actual.unique.gauntletCrit,150,'saved Lightning Storm activates gloves');
change('abilityId','flameBreath','select-one');
assert.equal(current().combat.abilityId,'flameBreath','selecting a skill updates combat conditions');
assert.equal(current().combat.damageType,'fire','Flame Breath automatically selects Fire');
assert.equal(current().combat.attackType,'strong','Flame Breath automatically selects Strong Attack');
click('new-build');click('tab-combat');
assert(!app.innerHTML.includes('data-key="elementalStacks"'),'unequipped shoulder should hide stacks');
assert(!app.innerHTML.includes('data-key="unyieldingActive"'),'unequipped chest should hide immunity');
console.log('PASS: 11 equipped unique powers, pauldron stacks, Prism, Greaves, Gauntlets, Iron, immunity, belt, UI and per-build sync');
